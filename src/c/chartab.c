/* CKIT.EXE data-only module between hero.c and tiles.c: the character
 * tables, DGROUP 0ec6..1c41 -- the XP step past level 11, the spell lists by
 * level, race limits, the classes a race may take, starting ages and the age
 * brackets, class minimums and alignments, the hit-point bonus by
 * constitution, each class's spell-slot row, the XP table, the spell slots,
 * the starting-money dice, the saving throws and the racial level caps.  Dark
 * Queen of Krynn's chartab.c, cut down to FRUA's six races and seven single
 * classes (DQK's 11-class XP steps, its starting items and its spell list
 * size differ).  Races run elf, half-elf, dwarf, gnome, halfling, human;
 * classes cleric, knight, fighter, paladin, ranger, magic-user, thief, then
 * monk and the multi-classes (gametext.c's class_names and race_names).
 *
 * herostat.c and charview.c read class_spell_rows[5], the magic-user's row,
 * as mu_spell_row.  Nothing in the image reads spells_by_level or
 * start_money_dice; their names are DQK's.  No string literals and no
 * routines; 0ec5, after hero.c's literals, is the link's word-alignment pad,
 * and the empty _TEXT sits at tiles.c's start.
 */

